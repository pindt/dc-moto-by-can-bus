/**
 * @file    SpiDrv_Lpspi.c
 * @brief   Backend: maps SpiDrv onto the RTD IP layer (Lpspi_Ip_*). The only file that includes
 *          Lpspi_Ip.h. Register access stays inside the RTD.
 */
#include "SpiDrv_Backend.h"
#include "SpiDrv_Baud.h"
#include "SpiDrv_Internal.h"
#include "Lpspi_Ip.h"

/* RAM copy of one tool generated external device. The RTD keeps a pointer to IpDev and reads
 * CCR/TCR/DeviceParams from it at every transmit, so this storage must live as long as SpiDrv. */
typedef struct
{
    Lpspi_Ip_ExternalDeviceType IpDev;
    Lpspi_Ip_DeviceParamsType   Params;
} SpiDrv_BeDevType;

static SpiDrv_BeDevType SpiDrv_BeDev[SPIDRV_MAX_DEVICES];

/* ------------------------------------------------------------------------------------------ */
static SpiDrv_StatusType SpiDrv_Be_MapStatus(Lpspi_Ip_StatusType Ip)
{
    SpiDrv_StatusType St;
    switch (Ip)
    {
        case LPSPI_IP_STATUS_SUCCESS: St = SPIDRV_OK;         break;
        case LPSPI_IP_FIFO_ERROR:     St = SPIDRV_FIFO_ERROR; break;
        case LPSPI_IP_TIMEOUT:        St = SPIDRV_TIMEOUT;    break;
        case LPSPI_IP_STATUS_FAIL:    St = SPIDRV_BUSY;       break;  /* command not accepted */
        default:                      St = SPIDRV_BAD_PARAM;  break;
    }
    return St;
}

static void SpiDrv_Be_EndCb(uint8 Instance, Lpspi_Ip_EventType Event)
{
    SpiDrv_OnTransferEnd(Instance,
        (LPSPI_IP_EVENT_END_TRANSFER == Event) ? SPIDRV_OK : SPIDRV_FIFO_ERROR);
}

static boolean SpiDrv_Be_FrameValid(uint8 Bits)
{
    return ((Bits >= LPSPI_IP_FRAMESIZE_MIN_U8) && (Bits <= LPSPI_IP_FRAMESIZE_MAX_U8)) ? TRUE : FALSE;
}

/* Build CCR / TCR from the SpiDrv device configuration (master and slave). */
static SpiDrv_StatusType SpiDrv_Be_BuildBus(SpiDrv_BeDevType *Be, const SpiDrv_DeviceConfigType *Dev,
                                            boolean IsMaster, uint32 FuncClockHz, uint32 BaudHz,
                                            uint32 *ActualHz)
{
    SpiDrv_BaudResultType R;
    uint32 Ccr;
    uint32 Tcr;
    SpiDrv_StatusType St = SpiDrv_Baud_Calc(FuncClockHz, BaudHz, Dev->Cs2ClkNs, Dev->Clk2CsNs,
                                            Dev->Cs2CsNs, IsMaster, &R);
    if (SPIDRV_OK == St)
    {
        Ccr = (uint32)(LPSPI_CCR_SCKPCS((uint32)R.SckPcs) | LPSPI_CCR_PCSSCK((uint32)R.PcsSck) |
                       LPSPI_CCR_SCKDIV((uint32)R.SckDiv) | LPSPI_CCR_DBT((uint32)R.Dbt));
        Tcr = (uint32)(LPSPI_TCR_WIDTH(0U) | LPSPI_TCR_CPOL((uint32)Dev->Cpol) |
                       LPSPI_TCR_CPHA((uint32)Dev->Cpha) | LPSPI_TCR_PRESCALE((uint32)R.Prescale) |
                       LPSPI_TCR_PCS((uint32)Dev->Pcs) |
                       LPSPI_TCR_CONT((TRUE == Dev->Continuous) ? 1U : 0U));
#if (LPSPI_IP_DUAL_CLOCK_MODE == STD_ON)
        Be->IpDev.Ccr[0U] = Ccr;     /* alternate clock entry [1] keeps the tool value */
        Be->IpDev.Tcr[0U] = Tcr;
#else
        Be->IpDev.Ccr = Ccr;
        Be->IpDev.Tcr = Tcr;
#endif
        if (NULL_PTR != ActualHz)
        {
            *ActualHz = R.ActualHz;
        }
    }
    return St;
}

/* ------------------------------------ unit level ------------------------------------------ */
SpiDrv_StatusType SpiDrv_Be_UnitInit(const SpiDrv_UnitConfigType *Unit)
{
    const Lpspi_Ip_ConfigType *Cfg = (const Lpspi_Ip_ConfigType *)Unit->IpConfig;

    if ((NULL_PTR == Cfg) || (Cfg->Instance != Unit->Instance))
    {
        return SPIDRV_BAD_PARAM;
    }
#if (LPSPI_IP_SLAVE_SUPPORT == STD_ON)
    if (Cfg->SlaveMode != ((SPIDRV_ROLE_SLAVE == Unit->Role) ? TRUE : FALSE))
    {
        return SPIDRV_BAD_PARAM;    /* role differs from CFGR1[MASTER] generated by the tool */
    }
#else
    if (SPIDRV_ROLE_SLAVE == Unit->Role)
    {
        return SPIDRV_NOT_SUPPORTED;
    }
#endif
    return SpiDrv_Be_MapStatus(Lpspi_Ip_Init(Cfg));
}

SpiDrv_StatusType SpiDrv_Be_UnitDeInit(uint8 Instance)
{
    return SpiDrv_Be_MapStatus(Lpspi_Ip_DeInit(Instance));
}

SpiDrv_StatusType SpiDrv_Be_SetMode(uint8 Instance, SpiDrv_ModeType Mode)
{
    return SpiDrv_Be_MapStatus(Lpspi_Ip_UpdateTransferMode(Instance,
        (SPIDRV_MODE_INTERRUPT == Mode) ? LPSPI_IP_INTERRUPT : LPSPI_IP_POLLING));
}

SpiDrv_UnitStatusType SpiDrv_Be_GetStatus(uint8 Instance)
{
    SpiDrv_UnitStatusType S;
    switch (Lpspi_Ip_GetStatus(Instance))
    {
        case LPSPI_IP_IDLE:  S = SPIDRV_UNIT_IDLE;   break;
        case LPSPI_IP_BUSY:  S = SPIDRV_UNIT_BUSY;   break;
        case LPSPI_IP_FAULT: S = SPIDRV_UNIT_FAULT;  break;
        default:             S = SPIDRV_UNIT_UNINIT; break;
    }
    return S;
}

void SpiDrv_Be_Cancel(uint8 Instance)
{
    Lpspi_Ip_Cancel(Instance);
}

void SpiDrv_Be_Manage(uint8 Instance)
{
    Lpspi_Ip_ManageBuffers(Instance);
}

/* ------------------------------------ device level ---------------------------------------- */
SpiDrv_StatusType SpiDrv_Be_DeviceInit(uint8 DevIdx, const SpiDrv_DeviceConfigType *Dev,
                                       uint8 UnitInstance, boolean IsMaster, uint32 FuncClockHz)
{
    SpiDrv_StatusType St = SPIDRV_OK;
    SpiDrv_BeDevType *Be;
    const Lpspi_Ip_ExternalDeviceType *Src;

    if ((DevIdx >= SPIDRV_MAX_DEVICES) || (NULL_PTR == Dev) || (NULL_PTR == Dev->IpDevice))
    {
        return SPIDRV_BAD_PARAM;
    }
    Src = (const Lpspi_Ip_ExternalDeviceType *)Dev->IpDevice;
    if ((Src->Instance != UnitInstance) || (NULL_PTR == Src->DeviceParams))
    {
        return SPIDRV_BAD_PARAM;
    }

    Be = &SpiDrv_BeDev[DevIdx];
    Be->IpDev  = *Src;                      /* copy of the tool data (incl. CCR/TCR) */
    Be->Params = *(Src->DeviceParams);
    Be->IpDev.DeviceParams = &Be->Params;

    if (0U != (Dev->OverrideMask & SPIDRV_OVR_FRAME))
    {
        if (FALSE == SpiDrv_Be_FrameValid(Dev->FrameBits)) { return SPIDRV_BAD_PARAM; }
        Be->Params.FrameSize = Dev->FrameBits;
    }
    if (0U != (Dev->OverrideMask & SPIDRV_OVR_LSB))
    {
        Be->Params.Lsb = Dev->LsbFirst;
    }
    if (0U != (Dev->OverrideMask & SPIDRV_OVR_DEFAULT))
    {
        Be->Params.DefaultData = Dev->DefaultData;
    }
    if (0U != (Dev->OverrideMask & SPIDRV_OVR_BUS))
    {
        St = SpiDrv_Be_BuildBus(Be, Dev, IsMaster, FuncClockHz, Dev->BaudHz, NULL_PTR);
    }
    return St;
}

SpiDrv_StatusType SpiDrv_Be_SetBaud(uint8 DevIdx, const SpiDrv_DeviceConfigType *Dev,
                                    boolean IsMaster, uint32 FuncClockHz, uint32 BaudHz,
                                    uint32 *ActualHz)
{
    if (DevIdx >= SPIDRV_MAX_DEVICES)
    {
        return SPIDRV_BAD_PARAM;
    }
    return SpiDrv_Be_BuildBus(&SpiDrv_BeDev[DevIdx], Dev, IsMaster, FuncClockHz, BaudHz, ActualHz);
}

SpiDrv_StatusType SpiDrv_Be_SetFrameSize(uint8 DevIdx, uint8 FrameBits)
{
    if ((DevIdx >= SPIDRV_MAX_DEVICES) || (FALSE == SpiDrv_Be_FrameValid(FrameBits)))
    {
        return SPIDRV_BAD_PARAM;
    }
    return SpiDrv_Be_MapStatus(Lpspi_Ip_UpdateFrameSize(&SpiDrv_BeDev[DevIdx].IpDev, FrameBits));
}

SpiDrv_StatusType SpiDrv_Be_SetLsb(uint8 DevIdx, boolean LsbFirst)
{
    if (DevIdx >= SPIDRV_MAX_DEVICES)
    {
        return SPIDRV_BAD_PARAM;
    }
    return SpiDrv_Be_MapStatus(Lpspi_Ip_UpdateLsb(&SpiDrv_BeDev[DevIdx].IpDev, LsbFirst));
}

SpiDrv_StatusType SpiDrv_Be_SetDefaultData(uint8 DevIdx, uint32 DefaultData)
{
    if (DevIdx >= SPIDRV_MAX_DEVICES)
    {
        return SPIDRV_BAD_PARAM;
    }
    return SpiDrv_Be_MapStatus(Lpspi_Ip_UpdateDefaultTransmitData(&SpiDrv_BeDev[DevIdx].IpDev, DefaultData));
}

/* ------------------------------------ transfers ------------------------------------------- */
/* The RTD prototypes take non-const uint8* although the TX buffer is only read. */
SpiDrv_StatusType SpiDrv_Be_Sync(uint8 DevIdx, const uint8 *Tx, uint8 *Rx,
                                 uint16 Length, uint32 TimeoutUs)
{
    return SpiDrv_Be_MapStatus(Lpspi_Ip_SyncTransmit(&SpiDrv_BeDev[DevIdx].IpDev,
                                                     (uint8 *)Tx, Rx, Length, TimeoutUs));
}

SpiDrv_StatusType SpiDrv_Be_Async(uint8 DevIdx, const uint8 *Tx, uint8 *Rx, uint16 Length)
{
    return SpiDrv_Be_MapStatus(Lpspi_Ip_AsyncTransmit(&SpiDrv_BeDev[DevIdx].IpDev,
                                                      (uint8 *)Tx, Rx, Length, &SpiDrv_Be_EndCb));
}
